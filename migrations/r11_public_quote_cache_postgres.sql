-- R1.1 PUBLIC quote-cache tables. DBA review and backup REQUIRED.
-- A cached observation is NOT a PIT research dataset or execution quote.
BEGIN;
CREATE TABLE IF NOT EXISTS public_quote_snapshots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(32) NOT NULL,
    symbol VARCHAR(32) NOT NULL,
    source_id VARCHAR(96) NOT NULL,
    asset_class VARCHAR(32) NOT NULL,
    product_type VARCHAR(32) NOT NULL,
    metric VARCHAR(32) NOT NULL,
    value FLOAT NOT NULL CHECK(value > 0),
    unit VARCHAR(32) NOT NULL,
    currency VARCHAR(8) NOT NULL,
    collected_at_utc TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    source_display_time VARCHAR(96) NOT NULL DEFAULT '',
    source_timestamp_utc TIMESTAMP WITHOUT TIME ZONE NULL,
    time_quality VARCHAR(32) NOT NULL CHECK(
        time_quality IN ('time_unverified','daily_observation','provider_update_timestamp')
    ),
    request_duration_ms INTEGER NOT NULL CHECK(request_duration_ms >= 0),
    source_record_sha256 VARCHAR(64) NOT NULL,
    source_record_json TEXT NOT NULL,
    observation_sha256 VARCHAR(64) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_public_quote_snapshots_kind ON public_quote_snapshots(kind);
CREATE INDEX IF NOT EXISTS ix_public_quote_snapshots_symbol ON public_quote_snapshots(symbol);
CREATE INDEX IF NOT EXISTS ix_public_quote_snapshots_collected_at_utc ON public_quote_snapshots(collected_at_utc);
CREATE INDEX IF NOT EXISTS ix_public_quote_snapshots_key_recent ON public_quote_snapshots(kind,symbol,id DESC);
CREATE TABLE IF NOT EXISTS public_quote_fetch_attempts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(32) NOT NULL,
    symbol VARCHAR(32) NOT NULL,
    attempted_at_utc TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    duration_ms INTEGER NOT NULL CHECK(duration_ms >= 0),
    state VARCHAR(24) NOT NULL CHECK(state IN ('success','failure')),
    error_code VARCHAR(64) NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS ix_public_quote_fetch_attempts_kind ON public_quote_fetch_attempts(kind);
CREATE INDEX IF NOT EXISTS ix_public_quote_fetch_attempts_symbol ON public_quote_fetch_attempts(symbol);
CREATE INDEX IF NOT EXISTS ix_public_quote_fetch_attempts_attempted_at_utc ON public_quote_fetch_attempts(attempted_at_utc);
CREATE INDEX IF NOT EXISTS ix_public_quote_attempts_key_recent ON public_quote_fetch_attempts(kind,symbol,id DESC);
-- Preserve a complete append-only history on managed PostgreSQL.
CREATE OR REPLACE FUNCTION reject_public_quote_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Public quote ledger is append-only' USING ERRCODE = '23514';
END;
$$;
DROP TRIGGER IF EXISTS public_quote_snapshots_append_only ON public_quote_snapshots;
CREATE TRIGGER public_quote_snapshots_append_only BEFORE UPDATE OR DELETE
ON public_quote_snapshots FOR EACH ROW EXECUTE FUNCTION reject_public_quote_mutation();
DROP TRIGGER IF EXISTS public_quote_attempts_append_only ON public_quote_fetch_attempts;
CREATE TRIGGER public_quote_attempts_append_only BEFORE UPDATE OR DELETE
ON public_quote_fetch_attempts FOR EACH ROW EXECUTE FUNCTION reject_public_quote_mutation();
COMMIT;
