-- R1 PostgreSQL migration. Manual DBA review REQUIRED before production.
-- Apply in one transaction to a backed-up database. No legacy table modification.
BEGIN;
CREATE TABLE IF NOT EXISTS dataset_releases (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint VARCHAR(64) NOT NULL UNIQUE,
    asset_class VARCHAR(32) NOT NULL,
    product_type VARCHAR(32) NOT NULL,
    source_id VARCHAR(96) NOT NULL,
    symbol VARCHAR(24) NOT NULL,
    venue VARCHAR(24) NOT NULL,
    currency VARCHAR(8) NOT NULL,
    adjustment VARCHAR(24) NOT NULL,
    volume_unit VARCHAR(24) NOT NULL,
    date_from DATE NOT NULL,
    date_to DATE NOT NULL,
    collected_at_utc TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    raw_sha256 VARCHAR(64) NOT NULL,
    rows_sha256 VARCHAR(64) NOT NULL,
    row_count INTEGER NOT NULL CHECK (row_count BETWEEN 1 AND 370),
    status VARCHAR(32) NOT NULL CHECK (status = 'provider_recorded'),
    quality_state VARCHAR(40) NOT NULL CHECK (quality_state = 'schema_validated_only'),
    schema_version VARCHAR(16) NOT NULL CHECK (schema_version = 'r1.0'),
    raw_payload_json TEXT NOT NULL,
    CHECK (date_from <= date_to),
    CHECK (length(raw_sha256) = 64 AND length(rows_sha256) = 64)
);
CREATE INDEX IF NOT EXISTS ix_dataset_releases_symbol ON dataset_releases (symbol);
CREATE TABLE IF NOT EXISTS dataset_price_observations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    release_id INTEGER NOT NULL REFERENCES dataset_releases(id) ON DELETE RESTRICT,
    obs_date DATE NOT NULL,
    open FLOAT NOT NULL,
    high FLOAT NOT NULL,
    low FLOAT NOT NULL,
    close FLOAT NOT NULL,
    volume FLOAT NOT NULL,
    amount FLOAT NOT NULL,
    CONSTRAINT uq_dataset_release_date UNIQUE (release_id, obs_date),
    CHECK (low > 0 AND low <= open AND low <= close AND
           high >= open AND high >= close AND volume >= 0 AND amount >= 0)
);
CREATE INDEX IF NOT EXISTS ix_dataset_price_observations_release_id ON dataset_price_observations(release_id);
CREATE INDEX IF NOT EXISTS ix_dataset_price_observations_obs_date ON dataset_price_observations(obs_date);

CREATE OR REPLACE FUNCTION reject_dataset_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'R1 dataset release ledger is append-only; create a new version'
      USING ERRCODE = '23514';
END;
$$;
DROP TRIGGER IF EXISTS dataset_releases_append_only ON dataset_releases;
CREATE TRIGGER dataset_releases_append_only
    BEFORE UPDATE OR DELETE ON dataset_releases
    FOR EACH ROW EXECUTE FUNCTION reject_dataset_mutation();
DROP TRIGGER IF EXISTS dataset_observations_append_only ON dataset_price_observations;
CREATE TRIGGER dataset_observations_append_only
    BEFORE UPDATE OR DELETE ON dataset_price_observations
    FOR EACH ROW EXECUTE FUNCTION reject_dataset_mutation();
COMMIT;

